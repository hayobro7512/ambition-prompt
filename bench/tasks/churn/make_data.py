"""Generate the synthetic churn dataset (customers.csv) and the judge-only answer key (truth.md).

Deterministic: `python3 make_data.py` always writes the same files. The planted story:
  * Not finishing onboarding is the main churn driver (monthly hazard x2.8).
  * Paid-social ads started 2024-02; those signups mostly skip onboarding, so paid_social LOOKS
    like a big driver, but within each onboarding group its effect is small (x1.15): a Simpson trap.
  * The Basic price rise ($19 -> $25 in 2024-03) adds a modest bump (x1.35) for Basic only.
  * Support tickets track onboarding, not churn itself: a confounded red herring.
  * The Team plan has few customers, so its rate is noisy.
Snapshot date: 2024-09-30.
"""
import csv
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
rng = random.Random(20241029)

MONTHS = [f"{y}-{m:02d}" for y in (2023, 2024) for m in range(1, 13)][:21]  # 2023-01 .. 2024-09
PRICE = {"basic": 19, "pro": 49, "team": 99}


def poisson(lam):
    k, p, L = 0, 1.0, 2.718281828 ** -lam
    while True:
        p *= rng.random()
        if p < L:
            return k
        k += 1


rows = []
for i in range(600):
    signup = rng.choice(MONTHS[:-1])
    paid_ok = signup >= "2024-02"
    channel = rng.choices(["organic", "partner", "paid_social"], [5, 2, 6 if paid_ok else 0])[0]
    plan = rng.choices(["basic", "pro", "team"], [6, 3.3, 0.7])[0]
    onboard = rng.random() < (0.3 if channel == "paid_social" else 0.75)
    seats = {"basic": rng.randint(1, 3), "pro": rng.randint(2, 10), "team": rng.randint(8, 40)}[plan]
    churn_month = ""
    for m in MONTHS[MONTHS.index(signup) + 1:]:
        h = 0.022
        h *= 1.0 if onboard else 2.8
        h *= 1.15 if channel == "paid_social" else 1.0
        h *= 1.35 if (plan == "basic" and m >= "2024-03") else 1.0
        h *= 0.6 if plan == "team" else 1.0
        if rng.random() < h:
            churn_month = m
            break
    end = churn_month or "2024-09"
    price = 25 if (plan == "basic" and end >= "2024-03") else PRICE[plan]
    logins = poisson((4 if churn_month else 14) * (1.0 if onboard else 0.7) * (seats ** 0.3))
    tickets = poisson(2.4 if not onboard else 0.7)
    rows.append({
        "customer_id": f"C{1000 + i}", "signup_month": signup, "plan": plan, "monthly_price": price,
        "seats": seats, "acquisition_channel": channel, "onboarding_completed": "Y" if onboard else "N",
        "logins_last_30d": logins, "support_tickets_90d": tickets,
        "churned": "Y" if churn_month else "N", "churn_month": churn_month,
    })

with open(os.path.join(HERE, "customers.csv"), "w", newline="") as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0]))
    w.writeheader()
    w.writerows(rows)


# ---- answer key, computed from the rows actually written -------------------------------------
def rate(sub):
    n = len(sub)
    c = sum(r["churned"] == "Y" for r in sub)
    return f"{c}/{n} = {100 * c / n:.0f}%" if n else "n/a"


def hazard(sub):
    # churn events per 100 customer-months at risk (corrects for tenure: recent signups had less time to churn)
    months_at_risk = 0
    for r in sub:
        end = r["churn_month"] or "2024-09"
        months_at_risk += MONTHS.index(end) - MONTHS.index(r["signup_month"])
    c = sum(r["churned"] == "Y" for r in sub)
    return f"{c} churns / {months_at_risk} cust-months = {100 * c / max(1, months_at_risk):.1f} per 100"


def mean(xs):
    return sum(xs) / len(xs) if xs else float("nan")


L = ["# Judge-only answer key for customers.csv (never shown to optimizers or the executor)", "",
     "Generated by make_data.py. Numbers below are exact counts from the file. 'Churn rate' = share of customers "
     "in the group who ever churned (ever-churned, not monthly).", "",
     "## Generating process (what the simulator did)", "",
     "1. Not finishing onboarding: monthly churn hazard x2.8.",
     "2. paid_social (ads started 2024-02): x1.15 on top, and only ~30% of these signups finish onboarding.",
     "3. Basic price rise $19 -> $25 in 2024-03: x1.35 for Basic customers from that month on.",
     "4. Support tickets depend on onboarding status only, never on churn (a confounded red herring).",
     "5. Team plan: x0.6, and few customers, so its rate is noisy.", "",
     "## What the sample shows (score claims against THESE numbers, not the multipliers above)", "",
     "- Onboarding status is the clearest driver (about 2.5x the tenure-corrected hazard).",
     "- paid_social's tenure-corrected hazard is the highest of any channel. Part of that is its low onboarding rate; "
     "in this sample it stays elevated within onboarding groups too, but those cells are small. "
     "Raw ever-churned rates hide all this because paid_social customers are recent (tenure bias).",
     "- Basic churn rose after the 2024-03 price change, but Pro also rose, so the price-specific part is modest.",
     "- Tickets look linked to churn overall but not within onboarding groups.",
     "- Monthly churn is noisy (small counts); the trend is roughly 3% -> 4.5%.",
     "A strong answer: corrects for tenure, separates onboarding from channel, tests the support-ticket belief, "
     "flags small n, and proposes a test that would confirm the cause.", "",
     "## Monthly churn (churned that month / active at start of month)", ""]
for m in MONTHS[-10:]:
    active = [r for r in rows if r["signup_month"] < m and (not r["churn_month"] or r["churn_month"] >= m)]
    ch = sum(r["churn_month"] == m for r in active)
    L.append(f"- {m}: {ch}/{len(active)} = {100 * ch / max(1, len(active)):.1f}%")
L += ["", "## Tenure-corrected monthly churn hazard by group (the right comparison)", ""]
for name, key, vals in (("channel", "acquisition_channel", ("organic", "partner", "paid_social")),
                        ("onboarding_completed", "onboarding_completed", ("Y", "N")),
                        ("plan", "plan", ("basic", "pro", "team"))):
    for v in vals:
        L.append(f"- {name}={v}: {hazard([r for r in rows if r[key] == v])}")
for ob in "YN":
    for ch in ("organic", "partner", "paid_social"):
        L.append(f"- onboarded={ob}, channel={ch}: "
                 f"{hazard([r for r in rows if r['onboarding_completed'] == ob and r['acquisition_channel'] == ch])}")
bas = [r for r in rows if r["plan"] == "basic"]
def hz_window(sub, lo, hi):
    risk = c = 0
    for r in sub:
        for m in MONTHS[MONTHS.index(r["signup_month"]) + 1:]:
            if r["churn_month"] and m > r["churn_month"]:
                break
            if lo <= m <= hi:
                risk += 1
                c += r["churn_month"] == m
    return f"{c}/{risk} = {100 * c / max(1, risk):.1f} per 100 cust-months"
for p in ("basic", "pro"):
    sub = [r for r in rows if r["plan"] == p]
    L.append(f"- plan={p} before price change (2023-06..2024-02): {hz_window(sub, '2023-06', '2024-02')}; "
             f"after (2024-03..2024-09): {hz_window(sub, '2024-03', '2024-09')}")
L += ["", "## Ever-churned rate by group (misleading: ignores tenure; recent paid_social signups had less time)", ""]
for ch in ("organic", "partner", "paid_social"):
    sub = [r for r in rows if r["acquisition_channel"] == ch]
    L.append(f"- channel={ch}: {rate(sub)}; onboarded Y: {rate([r for r in sub if r['onboarding_completed'] == 'Y'])}; "
             f"onboarded N: {rate([r for r in sub if r['onboarding_completed'] == 'N'])}")
for ob in "YN":
    L.append(f"- onboarding_completed={ob}: {rate([r for r in rows if r['onboarding_completed'] == ob])}")
for p in ("basic", "pro", "team"):
    L.append(f"- plan={p}: {rate([r for r in rows if r['plan'] == p])}")
ps = [r for r in rows if r["acquisition_channel"] == "paid_social"]
L.append(f"- share of paid_social signups that completed onboarding: "
         f"{sum(r['onboarding_completed'] == 'Y' for r in ps)}/{len(ps)}")
L += ["", "## Support tickets (mean tickets_90d)", ""]
for ob in "YN":
    for c in "YN":
        sub = [r["support_tickets_90d"] for r in rows if r["onboarding_completed"] == ob and r["churned"] == c]
        L.append(f"- onboarded={ob}, churned={c}: {mean(sub):.2f} (n={len(sub)})")
L += ["", "Within each onboarding group, churned and retained customers file a similar number of tickets.", ""]
with open(os.path.join(HERE, "truth.md"), "w") as f:
    f.write("\n".join(L))
print(f"wrote {len(rows)} rows")
